# joins the PR (reconcilable) row onto each base row. The FE /a2a/payment reconciliation dot column
# is driven by that join, so every tracked payment needs a matching base row here too.
PT_TABLE="${PAYMENT_TRANSACTIONS_TABLE_NAME:-calytics-a2a-payment-transactions}"
# Match-conflicts table (DEC-062): when the matcher DEFERS an ambiguous same-(amount,currency) group it
# writes an over-complete conflict record (every payment + every contested credit + the full per-pair
# condition matrix) so a human or LLM agent can reverse-engineer the decision. We seed one for the 008/009
# shared-family-IBAN pair so the table is exercised 1:1 with live.
CONFLICTS_TABLE="${MATCH_CONFLICTS_TABLE_NAME:-payment-reconciliation-local-match-conflicts}"
# Resolve the client these fixtures attach to. The FE /a2a/payment table is
