#!/bin/bash

# =============================================================================
# Seed local A2A payments (+ reconciliation PR rows) — 1:1 with live shape
# =============================================================================
# Populates `calytics-a2a-local-payments` with ~26 fixture rows spanning every
# (status × session_status × payment_tracking_enabled × reconciliation_status)
# combination operational tooling renders, AND — for every tracked payment —
# a matching `calytics-shared-local-reconcilable-transactions` (PR) row with the
# exact production item shape (mandate_id PK = clientId#tenantId#paymentId,
# sk = TRANSACTION#paymentId, additional_information.{endToEndId,senderIban,
# instant,purpose}, match_metadata for reconciled rows).
#
# Drives the calytics-fe /a2a/payment table: the reconciliation dot column shows
# green (Reconciled) / blue (Pending) / amber (AmbiguousMatch) / red (Unmatchable)
# for tracked rows, grey (Not tracked) for successful-but-untracked, faint for N/A.
#
# Idempotent: every payment_id is `seed-a2a-*`; we delete-then-put both tables.
#
# Usage:   cal seed a2a-payments
# Env:     AWS_ENDPOINT_URL, AWS_REGION, PAYMENTS_TABLE_NAME,
#          RECONCILABLE_TRANSACTIONS_TABLE_NAME, SEED_A2A_CLIENT_ID
# =============================================================================

