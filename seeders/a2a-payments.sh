# locally-seeded main client — whose id is a random uuid generated by be-admin's
# seed:clients (CPM refactor, Jun 2026), no longer the historical pinned uuid.
# Resolve it from Postgres (the same users -> user_clients join be-admin uses),
# honouring an explicit SEED_A2A_CLIENT_ID override, and fall back to the historical
# fixture uuid only when Postgres is unreachable (pure-DynamoDB standalone usage).
SEED_A2A_CLIENT_EMAIL="${SEED_A2A_CLIENT_EMAIL:-main.client@gmail.com}"
POSTGRES_HOST="${POSTGRES_HOST:-localhost}"
POSTGRES_PORT="${POSTGRES_PORT:-5432}"
POSTGRES_USER="${POSTGRES_USER:-postgres}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-register}"
POSTGRES_DB="${POSTGRES_DB:-calytics-admin}"
FALLBACK_CLIENT_ID="9f8a1f8c-56fd-43f9-b0dd-db0c86cf424a"

resolve_a2a_client_id() {
    command -v psql >/dev/null 2>&1 || return 0
    PGPASSWORD="$POSTGRES_PASSWORD" psql -h "$POSTGRES_HOST" -p "$POSTGRES_PORT" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -t -A -q \
        -c "SELECT uc.client_id FROM user_clients uc JOIN users u ON u.user_id = uc.user_id WHERE u.email = '$SEED_A2A_CLIENT_EMAIL' LIMIT 1;" 2>/dev/null | grep -v '^$' | head -1 || true
}

if [ -n "${SEED_A2A_CLIENT_ID:-}" ]; then
    CLIENT_ID="$SEED_A2A_CLIENT_ID"
else
    CLIENT_ID="$(resolve_a2a_client_id)"
    [ -z "$CLIENT_ID" ] && CLIENT_ID="$FALLBACK_CLIENT_ID"
fi

