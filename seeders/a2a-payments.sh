              pay("seed-a2a-009","Sister P","Reconciliation test 6")],
  "credits":[credit("6500002071","Max P"),credit("6500002072","Sister P")],
  "evaluations":[ev("seed-a2a-008","6500002071"),ev("seed-a2a-008","6500002072"),
                 ev("seed-a2a-009","6500002071"),ev("seed-a2a-009","6500002072")],
  "summary":"Two A2A payments (seed-a2a-008, seed-a2a-009) of EUR 2.07 from the same family IBAN "
